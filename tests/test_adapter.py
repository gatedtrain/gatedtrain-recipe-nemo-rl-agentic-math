class TestMakeDataMeta(unittest.TestCase):

    def test_prompt_tokens_kept_only_for_a_reproduced_meta(self):
        """runtime/make_data.py without --tokenizer keeps the committed data_meta.json's prompt_tokens only when the
        rest of it is reproduced byte for byte, so a README run leaves the committed file unchanged."""
        rt = A.REPO / "runtime"                            # this checkout's committed files, not REAL
        md = runtime_namespace("make_data.py", (rt / "make_data.py").read_text(encoding="utf-8"))
        committed = (rt / "data" / "data_meta.json").read_bytes()
        meta = json.loads(committed)
        kept = meta.pop("prompt_tokens")
        self.assertEqual(md["kept_prompt_tokens"](meta, committed), kept)
        self.assertEqual(md["render"]({**meta, "prompt_tokens": kept}), committed)
        self.assertIsNone(md["kept_prompt_tokens"]({**meta, "seed": meta["seed"] + 1}, committed))
        self.assertIsNone(md["kept_prompt_tokens"](meta, md["render"](meta)))      # nothing to keep
        self.assertIsNone(md["kept_prompt_tokens"](meta, None))


