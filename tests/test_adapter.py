def runtime_namespace(name: str, text: str | None = None) -> dict:
    """The runtime module's namespace, compiled from its source text (never imported: no byte code in the area)."""
    path = REAL / name
    ns = {"__file__": str(path), "__name__": f"{Path(name).stem}_real"}
    exec(compile(text if text is not None else path.read_text(encoding="utf-8"), str(path), "exec"), ns)
    return ns


def _root_can_read() -> bool:
    return os.geteuid() == 0


def relabel(p: Path, env_id: str) -> Path:
    """The logs of a fixture copy renamed to another environment id (env_calls.jsonl and trajectories.jsonl)."""
    for name in ("env_calls.jsonl", "trajectories.jsonl"):
        rows = read_jsonl(p / name)
        for r in rows:
            r["env_id"] = env_id
        A.write_jsonl(p / name, rows)
    return p


class AgenticCase(unittest.TestCase):
    """One scenario per test that changes it (`fresh`); `self.sc` is shared by the read-only tests of a class."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = Path(tempfile.mkdtemp(prefix="gatedtrain-ext-agentic-"))
        cls.addClassCleanup(shutil.rmtree, cls.tmp, True)
        cls.n = 0
        cls.sc = A.AgenticScenario(cls.tmp / "shared")

    def fresh(self, **kw) -> A.AgenticScenario:
        type(self).n += 1
        return A.AgenticScenario(self.tmp / f"sc-{type(self).n}", **kw)

    def runs(self) -> Path:
        type(self).n += 1
        return self.tmp / f"runs-{type(self).n}"

    def probe(self) -> Path:
        type(self).n += 1
        return A.probe_copy(self.tmp / f"probe-{type(self).n}")

    def sliding(self, **kw) -> Path:
        type(self).n += 1
        return A.sliding_copy(self.tmp / f"sliding-{type(self).n}", **kw)

    # --- in-process checks ---

    def cuts(self, sc: A.AgenticScenario) -> list:
        return adapter().find_cuts(sc.out)[0]

    def log_problems(self, sc: A.AgenticScenario) -> list[str]:
        return adapter().consumption_problems(sc.out, sc.data, self.cuts(sc))

    def probe_problems(self, p: Path) -> list[str]:
        return adapter().consumption_problems(p, p / "data" / "shards", [(3, p / "cuts" / "checkpoint-3")])

    def sliding_problems(self, p: Path) -> list[str]:
        return adapter().consumption_problems(p, p / "data" / "shards", [(2, p / "cuts" / "checkpoint-2")])

    def check_problems(self, sc: A.AgenticScenario, launch: dict | None = None, **kw) -> list:
        cuts = self.cuts(sc)
        last = cuts[-1][1] if cuts else sc.out / "cuts" / "checkpoint-60"
        rec = launch if launch is not None else json.loads((sc.root / "launch.json").read_text())
        return adapter().checks(last_cut=last, base=sc.base, launch=rec, base_field="base", stage_out=sc.out,
                                data=sc.data, data_field="data", **kw)

    def assertProblem(self, msgs, text: str):
        flat = [m if isinstance(m, str) else f"{m.rule} {m.field}: {m.message}" for m in msgs]
        self.assertTrue(any(text in m for m in flat), f"expected a problem containing {text!r}; got {flat}")

    # --- CLI ---

    def passes(self, sc: A.AgenticScenario, **kw) -> Path:
        proc = sc.collect(self.runs(), **kw)
        self.assertIn(proc.returncode, (EXIT_OK, NOT_PASS), describe(proc))
        return parse_run_dir(proc.stdout)

    def refused(self, sc: A.AgenticScenario, rule: str, text: str | None = None, **kw):
        runs = self.runs()
        proc = sc.collect(runs, **kw)
        self.assertEqual(proc.returncode, EXIT_REFUSED, describe(proc))
        self.assertNotIn("Traceback", proc.stderr)
        errs = parse_errors(proc.stderr)
        hits = [e for e in errs if e["rule"] == rule and (text is None or text in e["message"])]
        self.assertTrue(hits, f"expected error[{rule}] {text!r}; got {errs}\n{describe(proc)}")
        self.assertFalse(runs.exists() and any(runs.iterdir()), "a refusal writes no run directory")
        return hits

    def unreadable(self, p: Path) -> None:
        if _root_can_read():
            self.skipTest("running as root: chmod 0 does not make a file unreadable")
        p.chmod(0)
        self.addCleanup(p.chmod, 0o644)


