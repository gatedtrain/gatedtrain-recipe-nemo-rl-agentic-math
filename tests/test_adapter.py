class TestLaunchRules(AgenticCase):

    def launch(self, req: dict, *, profile: str = "smoke", extra: list[str] = (), smoke: Path | None = None):
        type(self).n += 1
        return self.sc.launch(req, f"lr-{type(self).n}", profile=profile, extra=list(extra), smoke=smoke)

    def new(self) -> tuple[Path, Path]:
        type(self).n += 1
        return self.sc.new_run(f"lr-{type(self).n}")

    def refused_req(self, req: dict, text: str, *, profile: str = "smoke", field: str | None = None):
        proc, rec = self.launch(req, profile=profile)
        self.assertEqual(proc.returncode, EXIT_REFUSED, describe(proc))
        self.assertNotIn("Traceback", proc.stderr)
        self.assertIn(text, proc.stderr)
        if field is not None:
            self.assertIn(field, [e["field"] for e in parse_errors(proc.stderr)])
        self.assertFalse(rec.exists())

    def test_train_request_with_sidecar(self):
        out, spool = self.new()
        proc, rec = self.launch(self.sc.request(out, spool))
        self.assertEqual(proc.returncode, EXIT_OK, describe(proc))
        start, train, stop = proc.stdout.strip().splitlines()
        for tok in ("docker --context gatedtrain run -d --name gatedtrain-mathexec-mm-a10-agentic-smoke-", "--network none",
                    "--read-only", "--cap-drop ALL", "--tmpfs /tmp:rw,nosuid,nodev,noexec,size=4g", "--memory-swap 8g",
                    f":{A.EXECUTOR}:ro", f"{spool}:/spool:rw",
                    f"{A.IMAGE} {A.TRAIN_PY} -I {A.EXECUTOR}/executor_server.py --serve /spool/mathexec.sock"):
            self.assertIn(tok, start)
        self.assertNotIn(f"{self.sc.runtime}:{A.AREA10}:ro", start)        # never the area root
        self.assertNotIn("--gpus", start)
        for tok in ("--runtime=nvidia --gpus all", "--shm-size=16g", "-w /opt/nemo-rl", f"{spool}:/spool:rw",
                    f"{A.IMAGE} {A.TRAIN_PY} {A.AREA10}/run_agentic_nemo.py --profile smoke"):
            self.assertIn(tok, train)
        self.assertTrue(stop.startswith("docker --context gatedtrain stop gatedtrain-mathexec-mm-a10-agentic-smoke-"))
        record = json.loads(rec.read_text())
        self.assertEqual(record["sidecar"]["runtime"], {"kind": "container", "image": A.IMAGE, "venv_lock_sha256": None})
        self.assertIsNone(record["sidecar"]["interpreter_sha256"])
        self.assertEqual(record["sidecar"]["script_sha256"], file_sha256(self.sc.runtime / "executor" / "executor_server.py"))
        self.assertEqual(self.sc.recheck(rec).returncode, EXIT_OK)
        (self.sc.runtime / "executor" / "executor_server.py").write_text("# changed after the launch\n")
        self.addCleanup((self.sc.runtime / "executor" / "executor_server.py").write_text,
                        f"# fixture stand-in for {A.EXECUTOR}/executor_server.py; never executed\n")
        proc = self.sc.recheck(rec)
        self.assertEqual(proc.returncode, EXIT_REFUSED, describe(proc))
        self.assertIn("sidecar.script_sha256", proc.stderr)

